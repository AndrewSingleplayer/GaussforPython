JS_TYPE = {"i8": "number", "i16": "number", "i32": "number", "u8": "number", "u16": "number", "u32": "number",
           "f32": "number", "f64": "number", "bool": "boolean (0/1)", "i64": "BigInt", "u64": "BigInt"}


def render_js(prog, src, name):
    """ES module that loads <name>.wasm in a browser, a Web Worker or Node, with memory helpers."""
    def js_type(t):
        if t.is_ptr:
            return f"pointer to {t.pointee} (byte offset, number)"
        if t.is_void:
            return "nothing"
        return JS_TYPE.get(str(t), str(t))

    lines = [f"// {name}.mjs: loads {name}.wasm, generated by HA++ from {src}. Don't edit.",
             "// Works in browsers (Safari on iPhone included), Web Workers and Node 18+.",
             "//",
             f'//   import {{ load }} from "./{name}.mjs";',
             f'//   const lib = await load(new URL("./{name}.wasm", import.meta.url));',
             "//   const p = lib.alloc(1024);        // 1024 bytes of the module's memory, 16-byte aligned",
             "//   lib.f32(p, 256).set(values);      // typed-array view of that memory",
             "//   lib.exports.some_function(p, 256);",
             "//",
             "// Pointers are byte offsets into lib.memory; i64/u64 values are BigInt, other numbers are Number.",
             "// Views must be taken again after memory grows (lib.alloc can grow it): don't keep them.",
             ""]
    if prog.exports or prog.cpu_kernels:
        lines.append("// Exported functions:")
        for fn in prog.exports:
            params = ", ".join(f"{p.name}: {js_type(p.ty)}" for p in fn.params)
            lines.append(f"//   {fn.name}({params}) -> {js_type(fn.ret_ty)}")
        for k in prog.cpu_kernels:
            params = ", ".join(f"{p.name}: {js_type(p.ty)}" for p in k.params)
            lines.append(f"//   {k.name}_cpu({params}, groups_x, groups_y, groups_z)  (kernel, run on the CPU)")
        lines.append("")
    sizes, offsets = [], []
    for st in prog.structs:
        if getattr(st, "is_std", False):
            continue
        size, _ = T.size_align(st)
        sizes.append(f"  {st.name}: {size},")
        offs = ", ".join(f"{f}: {o}" for (f, _), o in zip(st.fields, T.field_offsets(st)))
        offsets.append(f"  {st.name}: {{ {offs} }},")
    lines += ["// struct sizes and field offsets in bytes (the same layout as the C header)",
              "export const SIZEOF = {", *sizes, "};", "export const OFFSETOF = {", *offsets, "};", ""]
    lines += [
        "async function bytesOf(source) {",
        "  if (source instanceof ArrayBuffer || ArrayBuffer.isView(source)) return source;",
        "  const url = source instanceof URL ? source : new URL(String(source), globalThis.location?.href);",
        "  if (url.protocol === 'file:') {",
        "    const fs = await import('node:fs/promises');",
        "    return fs.readFile(url);",
        "  }",
        "  const r = await fetch(url);",
        "  if (!r.ok) throw new Error(`can't load ${url}: ${r.status}`);",
        "  return r.arrayBuffer();",
        "}",
        "",
        "/** Instantiate the module. `imports` provides the program's `extern fn` functions. */",
        "export async function load(source, imports = {}) {",
        "  const { instance } = await WebAssembly.instantiate(await bytesOf(source), { env: imports });",
        "  const exports = instance.exports;",
        "  const memory = exports.memory;",
        "  let top = Number(exports.__heap_base.value);",
        "  const align = (x, a) => Math.ceil(x / a) * a;",
        "  top = align(top, 16);",
        "  return {",
        "    exports,",
        "    memory,",
        "    /** Reserve `bytes` in the module's memory (grows it when needed); returns the byte offset. */",
        "    alloc(bytes, alignment = 16) {",
        "      const p = align(top, alignment);",
        "      const end = p + bytes;",
        "      if (end > memory.buffer.byteLength) memory.grow(Math.ceil((end - memory.buffer.byteLength) / 65536));",
        "      top = end;",
        "      return p;",
        "    },",
        "    /** Current end of reserved memory; reset(mark) frees everything reserved after it. */",
        "    mark() { return top; },",
        "    reset(mark) { top = mark; },",
        "    u8: (p, n) => new Uint8Array(memory.buffer, p, n),",
        "    u16: (p, n) => new Uint16Array(memory.buffer, p, n),",
        "    u32: (p, n) => new Uint32Array(memory.buffer, p, n),",
        "    i32: (p, n) => new Int32Array(memory.buffer, p, n),",
        "    f32: (p, n) => new Float32Array(memory.buffer, p, n),",
        "    f64: (p, n) => new Float64Array(memory.buffer, p, n),",
        "  };",
        "}",
        ""]
    return "\n".join(lines)


def write_bridges(prog, out_dir, name, package, cls, targets, produced, tc, metal_src, log,
                  spirv_kernels=(), gpu_runtime=False, src=None):
    src = src or f"{name}.ha"
    files = {}
    has_metal = metal_src is not None and any(t.startswith(("ios", "macos")) for t in targets)
    check_kernel_names(prog)
    header_text = CHeader(prog).render(name, src, set(spirv_kernels), has_metal, gpu_runtime)
    inc = os.path.join(out_dir, "include")
    os.makedirs(inc, exist_ok=True)
    with open(os.path.join(inc, f"{name}.h"), "w") as f:
        f.write(header_text)
    with open(os.path.join(inc, "module.modulemap"), "w") as f:
        f.write(f'module {cls}Core {{\n    header "{name}.h"\n    export *\n}}\n')
    files["header"] = os.path.join(inc, f"{name}.h")
    if gpu_runtime:
        rt = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "gpu")
        shutil.copyfile(os.path.join(rt, "ha_gpu.h"), os.path.join(inc, "ha_gpu.h"))

    if any(t.startswith(("android", "linux", "windows")) for t in targets):
        pdir = package.replace(".", "/")
        for lang, render, ext in (("kotlin", render_kotlin, "kt"), ("java", render_java, "java")):
            d = os.path.join(out_dir, "android", lang, pdir)
            os.makedirs(d, exist_ok=True)
            path = os.path.join(d, f"{cls}.{ext}")
            with open(path, "w") as f:
                f.write(render(prog, src, name, package, cls, set(spirv_kernels), gpu_runtime))
            files[lang] = path

    pkg = make_xcframework(tc, out_dir, name, cls, produced, header_text, log)
    if pkg:
        write_swift_package(pkg, prog, src, name, cls)
        files["swift_package"] = pkg
        from .driver import show
        log(f"  built swift package  -> {show(pkg)} ({cls}Core.xcframework, no Xcode used)")

    if any(t.startswith("web") for t in targets):
        wdir = os.path.join(out_dir, "web")
        os.makedirs(wdir, exist_ok=True)
        with open(os.path.join(wdir, f"{name}.mjs"), "w") as f:
            f.write(render_js(prog, src, name))
        files["js"] = os.path.join(wdir, f"{name}.mjs")

    pydir = os.path.join(out_dir, "python")
    os.makedirs(pydir, exist_ok=True)
    with open(os.path.join(pydir, f"{name}.py"), "w") as f:
        f.write(render_python(prog, src, name))
    files["python"] = os.path.join(pydir, f"{name}.py")
    log(f"  built bridges        -> include/{name}.h, Kotlin/Java, Python"
        + (f", web/{name}.mjs" if "js" in files else ""))
    return files
