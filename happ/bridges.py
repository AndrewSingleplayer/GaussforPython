"""Language bridges: how C/C++, Swift, Kotlin/Java and Python call an HA++ library.

  include/<name>.h + module.modulemap   C, C++, Objective-C, Swift
  android/kotlin, android/java          Kotlin / Java (JNI glue is already inside the .so)
  apple/<Class>/                        Swift package: <Class>Core.xcframework (made without
                                        Xcode) + Swift wrapper that runs the kernels with Metal
  python/<name>.py                      ctypes bindings for PC tools and AI experiments
"""

